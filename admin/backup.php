$totalSizeBytes = 0;

foreach ($tablesList as $t) {
    $totalRows += (int)($t['Rows'] ?? 0);
    $totalSizeBytes += (int)($t['Data_length'] ?? 0) + (int)($t['Index_length'] ?? 0);
}

$totalSizeFormatted = round($totalSizeBytes / (1024 * 1024), 2) . ' MB';

$csrfToken = generate_csrf_token();
$pageTitle = "Database Backup - Admin Portal";
