<?php
/**
 * Admin Portal - 1-Click Database Backup & System Snapshot
 * Generates and downloads a complete SQL snapshot of all database tables and rows
 */

require_once __DIR__ . '/../config.php';
require_once __DIR__ . '/../db.php';
require_once __DIR__ . '/../includes/auth_check.php';

require_login();
require_admin();
$adminUser = current_user();
$db = get_db();

// Handle SQL Dump Download
if (isset($_GET['action']) && $_GET['action'] === 'download_sql') {
    $filename = 'craftbrew_backup_' . date('Y-m-d_His') . '.sql';

    header('Content-Type: application/sql; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Pragma: no-cache');
    header('Expires: 0');

    $out = fopen('php://output', 'w');

    fwrite($out, "-- ======================================================\n");
    fwrite($out, "-- CraftBrew Platform Database Backup Snapshot\n");
    fwrite($out, "-- Version: " . APP_VERSION . "\n");
    fwrite($out, "-- Timestamp: " . date('Y-m-d H:i:s') . "\n");
    fwrite($out, "-- Generated by: " . $adminUser['username'] . " (IP: " . get_client_ip() . ")\n");
    fwrite($out, "-- ======================================================\n\n");
    fwrite($out, "SET FOREIGN_KEY_CHECKS=0;\n");
    fwrite($out, "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n");
    fwrite($out, "SET time_zone = \"+00:00\";\n\n");

    // Fetch all tables
    $tables = $db->query("SHOW TABLES")->fetchAll(PDO::FETCH_COLUMN);

    foreach ($tables as $table) {
        fwrite($out, "-- ------------------------------------------------------\n");
        fwrite($out, "-- Table structure for table `{$table}`\n");
        fwrite($out, "-- ------------------------------------------------------\n");
        fwrite($out, "DROP TABLE IF EXISTS `{$table}`;\n");

        $createStmt = $db->query("SHOW CREATE TABLE `{$table}`")->fetch(PDO::FETCH_ASSOC);
        fwrite($out, $createStmt['Create Table'] . ";\n\n");

        fwrite($out, "-- Dumping data for table `{$table}`\n");
        $rows = $db->query("SELECT * FROM `{$table}`")->fetchAll(PDO::FETCH_ASSOC);

        if (!empty($rows)) {
            foreach ($rows as $row) {
                $cols = array_map(function($c) { return "`" . str_replace("`", "``", $c) . "`"; }, array_keys($row));
                $vals = array_map(function($v) use ($db) {
                    if (is_null($v)) return "NULL";
                    return $db->quote($v);
                }, array_values($row));

                fwrite($out, "INSERT INTO `{$table}` (" . implode(", ", $cols) . ") VALUES (" . implode(", ", $vals) . ");\n");
            }
            fwrite($out, "\n");
        }
    }

    fwrite($out, "SET FOREIGN_KEY_CHECKS=1;\n");
    fwrite($out, "-- Backup completed successfully.\n");
    fclose($out);

    log_admin_action('database_backup', "Downloaded full SQL database backup snapshot ({$filename})");
    exit;
}

// Fetch database telemetry
